#!/bin/sh
set -e

# Never replace configured secrets or a running deployment's settings.
if [ -e .env ]; then
    echo '.env already exists; edit it explicitly to preserve configured secrets.' >&2
    exit 1
fi
[ -n "${ADMIN_SEED_EMAIL:-}" ] || { echo 'Set ADMIN_SEED_EMAIL before generating configuration.' >&2; exit 1; }
[ -n "${ADMIN_SEED_PASSWORD:-}" ] || { echo 'Set ADMIN_SEED_PASSWORD before generating configuration.' >&2; exit 1; }
command -v openssl >/dev/null || { echo 'openssl is required to generate secrets.' >&2; exit 1; }
POSTGRES_PASSWORD="$(openssl rand -hex 32)"
ADMIN_SESSION_SECRET="$(openssl rand -hex 32)"
umask 077

# Compose interpolates double-quoted dotenv values: escape dollars as well as quotes
# and backslashes. The sentinel preserves trailing newlines in command substitution.
DOTENV_SEED_PASSWORD=$(
    printf '%s' "$ADMIN_SEED_PASSWORD" | sed 's/\\/\\\\/g; s/"/\\"/g; s/\$/$$/g'
    printf .
)
DOTENV_SEED_PASSWORD=${DOTENV_SEED_PASSWORD%.}

DOMAIN="${1:-}"

if [ -z "$DOMAIN" ]; then
    if [ -t 0 ]; then
        printf "Enter your domain (e.g., fuiz.example.com) or 'localhost' for local dev [default: localhost]: "
        read -r DOMAIN
    fi
    DOMAIN="${DOMAIN:-localhost}"
fi

NGINX_PORT="${NGINX_PORT:-80}"
BASE_PATH="${BASE_PATH:-/SEQuiz}"
case "$BASE_PATH" in
    /*) ;;
    *) echo 'BASE_PATH must start with /' >&2; exit 1 ;;
esac
case "$BASE_PATH" in
    *[!a-zA-Z0-9_/-]*|*/|*//*)
        echo 'BASE_PATH must use /name segments without a trailing slash' >&2
        exit 1
        ;;
esac

SCHEME="http"
WS_SCHEME="ws"

PUBLIC_HOST="$DOMAIN"
if [ "$NGINX_PORT" != "80" ]; then
    PUBLIC_HOST="$DOMAIN:$NGINX_PORT"
fi
WEB_URL="$SCHEME://$PUBLIC_HOST"
PLAY_URL="$WEB_URL"
DISPLAY_PLAY_URL="$PUBLIC_HOST$BASE_PATH"
BACKEND_URL="$WEB_URL$BASE_PATH/backend"
WS_BACKEND_URL="$WS_SCHEME://$PUBLIC_HOST$BASE_PATH/backend"
CORKBOARD_URL="$WEB_URL$BASE_PATH/media"
ALLOWED_ORIGINS="[\"$WEB_URL\"]"

if [ "$DOMAIN" = "localhost" ] || [ "$DOMAIN" = "127.0.0.1" ]; then
    SEED_DEMO_GAMES=true
else
    SEED_DEMO_GAMES=false
fi

{
cat <<EOF
# Generated by generate_config.sh on $(date -u +"%Y-%m-%dT%H:%M:%SZ")

# Domain and public Nginx port
FUIZ_DOMAIN=$DOMAIN
NGINX_PORT=$NGINX_PORT
BASE_PATH=$BASE_PATH

# Frontend environment variables
ORIGIN=$WEB_URL
PUBLIC_DISPLAY_PLAY_URL=$DISPLAY_PLAY_URL
PUBLIC_PLAY_URL=$PLAY_URL
PUBLIC_BACKEND_URL=$BACKEND_URL
PUBLIC_WS_URL=$WS_BACKEND_URL
PUBLIC_CORKBOARD_URL=$CORKBOARD_URL
PUBLIC_SELF_HOSTED=true

POSTGRES_DB=se_quiz
POSTGRES_USER=se_quiz
DB_PROVIDER=postgres
KV_PROVIDER=postgres
ADMIN_SEED_EMAIL=$ADMIN_SEED_EMAIL
EOF
printf '%s=%s\n' POSTGRES_PASSWORD "$POSTGRES_PASSWORD"
printf '%s=%s\n' DATABASE_URL "postgres://se_quiz:$POSTGRES_PASSWORD@postgres:5432/se_quiz"
printf '%s="%s"\n' ADMIN_SEED_PASSWORD "$DOTENV_SEED_PASSWORD"
printf '%s=%s\n' ADMIN_SESSION_SECRET "$ADMIN_SESSION_SECRET"
printf '%s=%s\n' SEED_DEMO_GAMES "$SEED_DEMO_GAMES"
cat <<EOF

# Game server CORS
FUIZ_ALLOWED_ORIGINS=$ALLOWED_ORIGINS

# Corkboard CORS
CORKBOARD_ALLOWED_ORIGINS=$ALLOWED_ORIGINS

# Activity and keyword AI are managed by ADMIN at $BASE_PATH/admin/llm.
# See .env.example for pgAdmin settings before starting Compose.
EOF
} > .env

echo "Configuration written to .env"
echo ""
echo "Public paths:"
echo "  - Web Frontend:  $WEB_URL$BASE_PATH/"
echo "  - Game Server:   $BACKEND_URL"
echo "  - Corkboard:     $CORKBOARD_URL"
echo ""
echo "To start Fuiz, run:"
echo "  docker compose up -d"
